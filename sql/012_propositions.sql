-- -----------------------------------------------------------------------------
-- Entretien : ce que le temps a tranché                                   (WKD-3)
--
-- Une proposition dont le week-end est passé n'attend plus de réponse, et une
-- proposition couverte par une absence a obtenu la sienne — qu'elle soit
-- venue d'un billet, du bot ou d'un départ déclaré à la main.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION entretenir_propositions() RETURNS INTEGER
LANGUAGE plpgsql AS $$
DECLARE
    v_touchees INTEGER := 0;
    v_lot      INTEGER;
BEGIN
    UPDATE proposition
       SET statut = 'realisee'
     WHERE statut = 'proposee'
       AND EXISTS (SELECT 1 FROM absence a
                    WHERE a.id_utilisateur = proposition.id_utilisateur
                      AND a.periode && proposition.periode);
    GET DIAGNOSTICS v_lot = ROW_COUNT;
    v_touchees := v_lot;

    UPDATE proposition
       SET statut = 'perimee'
     WHERE statut IN ('proposee', 'ecartee')
       AND upper(periode) < now();
    GET DIAGNOSTICS v_lot = ROW_COUNT;

    RETURN v_touchees + v_lot;
END $$;


-- -----------------------------------------------------------------------------
-- Repérer les week-ends libres                                       (WKD-1, WKD-4)
--
-- On cherche les fenêtres au-delà du délai demandé, puis on filtre. Sinon une
-- fenêtre à cheval sur l'horizon est tronquée et perd sa durée minimale.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION proposer_weekends(
    p_utilisateur  INTEGER,
    p_lieu         VARCHAR DEFAULT NULL,
    p_delai_jours  INTEGER DEFAULT 14,
    p_duree_heures INTEGER DEFAULT 48
) RETURNS SETOF proposition LANGUAGE plpgsql AS $$
BEGIN
    PERFORM entretenir_propositions();

    RETURN QUERY
    INSERT INTO proposition (id_utilisateur, periode, lieu)
    SELECT p_utilisateur, tstzrange(f.debut, f.fin, '[)'), p_lieu
      FROM fenetres_de_depart(p_utilisateur, now(),
                              now() + make_interval(days => p_delai_jours + 10),
                              p_duree_heures) f
     WHERE f.debut <= now() + make_interval(days => p_delai_jours)
       -- Ni déjà proposé, ni déjà refusé : revenir à la charge sur un week-end
       -- qu'on a décliné est le meilleur moyen de faire couper les alertes.
       AND NOT EXISTS (
           SELECT 1 FROM proposition p
            WHERE p.id_utilisateur = p_utilisateur
              AND p.periode && tstzrange(f.debut, f.fin, '[)')
              AND p.statut <> 'perimee')
       -- Ni déjà parti : une absence déclarée vaut réponse.
       AND NOT EXISTS (
           SELECT 1 FROM absence a
            WHERE a.id_utilisateur = p_utilisateur
              AND a.periode && tstzrange(f.debut, f.fin, '[)'))
    RETURNING *;
END $$;

COMMENT ON FUNCTION proposer_weekends IS
    'Crée une proposition par creux assez long commençant dans le délai donné.
     Idempotente : rejouée le lendemain, elle ne crée rien de nouveau (WKD-2).';


-- -----------------------------------------------------------------------------
-- Relancer, une fois                                                      (WKD-5)
--
-- Une seule relance, et seulement si la première annonce est restée sans
-- réponse. Pas de troisième.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION propositions_a_relancer(
    p_jours INTEGER DEFAULT 3
) RETURNS SETOF proposition LANGUAGE sql STABLE AS $$
    SELECT *
      FROM proposition
     WHERE statut = 'proposee'
       AND annoncee_le IS NOT NULL
       AND relancee_le IS NULL
       -- Jamais le jour de l'annonce : un week-end repéré trois jours avant
       -- serait annoncé et relancé dans la foulée.
       AND jour_de(annoncee_le) < jour_de(now())
       AND lower(periode) <= now() + make_interval(days => p_jours)
       AND lower(periode) > now()
     ORDER BY lower(periode);
$$;
