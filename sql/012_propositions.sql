--             EXISTS.
-- =============================================================================
-- 012 : propositions de week-end                              (WKD-1 à WKD-5)
--
-- Le système savait repérer un creux de deux jours, mais ne le disait que sur
-- demande. Il l'annonce désormais quinze jours avant, et relance une fois
-- trois jours avant.
--
-- Une proposition n'est pas une absence : elle s'affiche au calendrier et
-- n'a aucun effet sur le placement (WKD-1).
-- =============================================================================

CREATE TABLE IF NOT EXISTS proposition (
    id_proposition BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_utilisateur INTEGER      NOT NULL REFERENCES utilisateur (id_utilisateur)
                                ON DELETE CASCADE,
    periode        TSTZRANGE    NOT NULL CHECK (NOT isempty(periode)
                                                AND lower(periode) IS NOT NULL
                                                AND upper(periode) IS NOT NULL),
    lieu           VARCHAR(100),
    statut         VARCHAR(20)  NOT NULL DEFAULT 'proposee'
                                CHECK (statut IN ('proposee', 'ecartee',
                                                  'realisee', 'perimee')),
    annoncee_le    TIMESTAMPTZ,
    relancee_le    TIMESTAMPTZ,
    date_creation  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- WKD-2 : deux propositions en cours ne peuvent pas se chevaucher. Évite
    -- de reproposer le même week-end à chaque collecte, les bornes de la
    -- fenêtre bougeant de quelques heures d'une fois sur l'autre.
    CONSTRAINT proposition_sans_doublon
        EXCLUDE USING gist (id_utilisateur WITH =, periode WITH &&)
        WHERE (statut = 'proposee')
);

CREATE INDEX IF NOT EXISTS proposition_a_traiter
    ON proposition (statut, lower(periode));

COMMENT ON TABLE proposition IS
    'Suggestion de week-end, sans effet sur le planning. Devient une absence
     seulement si on retient un trajet (WKD-1).';


-- La notification doit pouvoir renvoyer à ce qu'elle annonce, sinon le bot ne
-- sait pas à quoi accrocher ses boutons.
ALTER TABLE notification
    ADD COLUMN IF NOT EXISTS id_proposition BIGINT
        REFERENCES proposition (id_proposition) ON DELETE CASCADE;


